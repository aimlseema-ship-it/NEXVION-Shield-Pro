import { jsPDF } from "jspdf";
import { RISK_CONFIG } from "./detection";

export function downloadScanReport(scan) {
  const doc = new jsPDF();
  const cfg = RISK_CONFIG[scan.riskLevel] || RISK_CONFIG.medium;
  const pageWidth = doc.internal.pageSize.getWidth();

  // Header bar
  doc.setFillColor(37, 99, 235);
  doc.rect(0, 0, pageWidth, 28, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(20);
  doc.setFont("helvetica", "bold");
  doc.text("NEXVION", 14, 18);
  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text("AI-Powered Spam & Scam Detection Report", 50, 18);

  let y = 42;
  doc.setTextColor(30, 30, 30);
  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.text("Scan Summary", 14, y);
  y += 8;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  const lines = [
    `Date: ${new Date(scan.created_date).toLocaleString()}`,
    `Scan Type: ${scan.scanType.toUpperCase()}`,
    `Platform: ${scan.platform || "N/A"}`,
    `Risk Level: ${cfg.label} (${scan.riskScore}/100)`,
    `Issues Found: ${scan.issues?.length || 0}`,
  ];
  lines.forEach((l) => {
    doc.text(l, 14, y);
    y += 6;
  });

  y += 4;
  doc.setFont("helvetica", "bold");
  doc.text("Scanned Content:", 14, y);
  y += 6;
  doc.setFont("helvetica", "normal");
  const inputLines = doc.splitTextToSize(scan.input || "N/A", pageWidth - 28);
  doc.text(inputLines, 14, y);
  y += inputLines.length * 5 + 6;

  if (scan.issues && scan.issues.length > 0) {
    doc.setFont("helvetica", "bold");
    doc.text("Detected Issues:", 14, y);
    y += 6;
    doc.setFont("helvetica", "normal");
    scan.issues.forEach((issue, i) => {
      const issueLines = doc.splitTextToSize(`${i + 1}. [${issue.severity.toUpperCase()}] ${issue.title}: ${issue.message}`, pageWidth - 28);
      if (y > 270) {
        doc.addPage();
        y = 20;
      }
      doc.text(issueLines, 14, y);
      y += issueLines.length * 5 + 2;
    });
  }

  y += 4;
  if (y > 250) {
    doc.addPage();
    y = 20;
  }
  doc.setFont("helvetica", "bold");
  doc.text("Safety Recommendations:", 14, y);
  y += 6;
  doc.setFont("helvetica", "normal");
  (scan.recommendations || []).forEach((rec) => {
    const recLines = doc.splitTextToSize(`• ${rec}`, pageWidth - 28);
    if (y > 270) {
      doc.addPage();
      y = 20;
    }
    doc.text(recLines, 14, y);
    y += recLines.length * 5 + 2;
  });

  // Footer
  const pageHeight = doc.internal.pageSize.getHeight();
  doc.setDrawColor(220, 220, 220);
  doc.line(14, pageHeight - 14, pageWidth - 14, pageHeight - 14);
  doc.setFontSize(8);
  doc.setTextColor(120, 120, 120);
  doc.text("Generated by NEXVION — This report is based on rule-based analysis and is for informational purposes only.", 14, pageHeight - 9);

  doc.save(`nexvion-report-${scan.id || Date.now()}.pdf`);
}